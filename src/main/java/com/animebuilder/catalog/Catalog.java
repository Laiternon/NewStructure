package com.animebuilder.catalog;

import com.animebuilder.structure.Structure;
import com.google.gson.JsonArray;
import com.google.gson.JsonObject;
import com.google.gson.JsonParser;
import com.mojang.logging.LogUtils;
import net.minecraft.commands.arguments.blocks.BlockStateParser;
import net.minecraft.core.BlockPos;
import net.minecraft.core.registries.BuiltInRegistries;
import net.minecraft.network.chat.Component;
import net.minecraft.resources.ResourceLocation;
import net.minecraft.world.level.block.Block;
import net.minecraft.world.level.block.Blocks;
import net.minecraft.world.level.block.state.BlockState;
import org.slf4j.Logger;

import java.io.IOException;
import java.io.InputStream;
import java.io.InputStreamReader;
import java.io.Reader;
import java.nio.charset.StandardCharsets;
import java.util.*;

/** Loads structure definitions (JSON, generated by the authoring tool) from the mod jar. */
public final class Catalog {
    private static final Logger LOGGER = LogUtils.getLogger();
    private static final String BASE = "/data/animebuilder/structures/";

    private static final Map<String, JsonObject> RAW = new LinkedHashMap<>();
    private static final Map<String, Structure> BUILT = new HashMap<>();
    private static boolean init;

    private Catalog() {}

    private static synchronized void init() {
        if (init) return;
        init = true;
        try (Reader r = open("index.json")) {
            JsonArray arr = JsonParser.parseReader(r).getAsJsonObject().getAsJsonArray("structures");
            for (var el : arr) {
                String id = el.getAsString();
                try (Reader fr = open(id + ".json")) {
                    RAW.put(id, JsonParser.parseReader(fr).getAsJsonObject());
                } catch (Exception e) {
                    LOGGER.error("[AnimeBuilder] cannot read structure {}", id, e);
                }
            }
        } catch (Exception e) {
            LOGGER.error("[AnimeBuilder] cannot read structure index", e);
        }
        LOGGER.info("[AnimeBuilder] {} structures available", RAW.size());
    }

    private static Reader open(String file) throws IOException {
        InputStream in = Catalog.class.getResourceAsStream(BASE + file);
        if (in == null) throw new IOException("missing resource " + BASE + file);
        return new InputStreamReader(in, StandardCharsets.UTF_8);
    }

    public static List<String> ids() { init(); return new ArrayList<>(RAW.keySet()); }

    public static List<String> categories() {
        init();
        Set<String> out = new LinkedHashSet<>();
        for (JsonObject o : RAW.values()) out.add(o.get("category").getAsString());
        return new ArrayList<>(out);
    }

    public static List<String> idsIn(String category) {
        init();
        List<String> out = new ArrayList<>();
        for (var e : RAW.entrySet()) if (e.getValue().get("category").getAsString().equals(category)) out.add(e.getKey());
        return out;
    }

    public static String nameOf(String id) {
        init();
        JsonObject o = RAW.get(id);
        return o == null ? id : o.get("name").getAsString();
    }

    public static synchronized Structure get(String id) {
        init();
        Structure s = BUILT.get(id);
        if (s != null) return s;
        JsonObject o = RAW.get(id);
        if (o == null) return null;
        try {
            s = build(id, o);
            BUILT.put(id, s);
        } catch (Exception e) {
            LOGGER.error("[AnimeBuilder] cannot build structure {}", id, e);
        }
        return s;
    }

    private static Structure build(String id, JsonObject o) {
        JsonArray pal = o.getAsJsonArray("palette");
        BlockState[] states = new BlockState[pal.size()];
        for (int i = 0; i < states.length; i++) states[i] = parse(pal.get(i).getAsString());
        JsonArray blocks = o.getAsJsonArray("blocks");
        Map<BlockPos, BlockState> map = new HashMap<>(blocks.size() / 4 + 16);
        for (int i = 0; i + 3 < blocks.size(); i += 4) {
            map.put(new BlockPos(blocks.get(i).getAsInt(), blocks.get(i + 1).getAsInt(), blocks.get(i + 2).getAsInt()), states[blocks.get(i + 3).getAsInt()]);
        }
        BlockState foundation = parse(o.has("foundation") ? o.get("foundation").getAsString() : "minecraft:cobblestone");
        return Structure.fromMap(id, o.get("category").getAsString(), Component.literal(o.get("name").getAsString()), foundation, map);
    }

    private static BlockState parse(String s) {
        try {
            return BlockStateParser.parseForBlock(BuiltInRegistries.BLOCK.asLookup(), s, false).blockState();
        } catch (Exception e) {
            LOGGER.error("[AnimeBuilder] cannot parse block state '{}': {}", s, e.getMessage());
            int br = s.indexOf('[');
            String name = br >= 0 ? s.substring(0, br) : s;
            Block b = BuiltInRegistries.BLOCK.get(new ResourceLocation(name));
            return b == Blocks.AIR && !name.equals("minecraft:air") ? Blocks.STONE_BRICKS.defaultBlockState() : b.defaultBlockState();
        }
    }
}
